#!/usr/bin/env python3
"""Build a sysroot overlay so `-Zbuild-std=std` targets os = "galexy".

This is the in-tree form of "fork rust-lang/rust as galexy-rust": instead of
carrying a whole compiler tree, the Galexy platform layer lives in `std-pal/`
at the repo root (one file per `std::sys` module, laid out exactly as it lands
inside `library/std/src/`), and this script produces a copy of the pinned
toolchain's `library/` with that tree installed and every `cfg_select!`
dispatcher taught about `target_os = "galexy"`. `library/` is never edited in
place; the overlay is rebuilt whenever the toolchain, this script, `std-pal/`,
or the ABI crate changes. Host rlibs stay symlinks to the real sysroot.

The syscall ABI is not duplicated: `sys/pal/galexy/abi.rs` is generated from
`crates/galexy-abi/src/lib.rs`, so std and the kernel cannot disagree about a
syscall number.

Usage: galexy-std-sysroot.py --out DIR     # prints DIR/<content-hash>/sysroot
"""

import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

PATCH_VERSION = "2"
REPO = Path(__file__).resolve().parent.parent
STD_PAL = REPO / "std-pal"
ABI_SRC = REPO / "crates/galexy-abi/src/lib.rs"

ABI_HEADER = """\
//! Generated by `scripts/galexy-std-sysroot.py` from
//! `crates/galexy-abi/src/lib.rs`. Do not edit; edit the crate.
#![allow(dead_code, missing_docs, missing_debug_implementations, unreachable_pub)]
#![allow(clippy::all)]

"""


def rustc_sysroot() -> Path:
    rustc = os.environ.get("RUSTC", "rustc")
    out = subprocess.check_output([rustc, "--print", "sysroot"], text=True)
    return Path(out.strip())


def patch_text(path: Path, old: str, new: str) -> None:
    text = path.read_text()
    if old not in text:
        sys.exit(f"galexy-std-sysroot: pattern missing in {path}:\n{old}")
    if text.count(old) != 1:
        sys.exit(f"galexy-std-sysroot: pattern not unique in {path}:\n{old}")
    path.write_text(text.replace(old, new, 1))


def insert_before(path: Path, anchor: str, new: str) -> None:
    patch_text(path, anchor, new + anchor)


def pal_files() -> list[Path]:
    return sorted(p for p in STD_PAL.rglob("*") if p.is_file())


def generate_abi(dest: Path) -> None:
    """The ABI crate is a single `no_std` file; strip its crate attributes
    and its test module and it is a plain std submodule."""
    lines = []
    skip_next = False
    for line in ABI_SRC.read_text().splitlines(keepends=True):
        if skip_next:
            skip_next = False
            continue
        if line.startswith("#!["):
            continue
        if line.strip() == "#[cfg(test)]":
            skip_next = True
            continue
        lines.append(line)
    dest.write_text(ABI_HEADER + "".join(lines))


def install_pal(std_src: Path) -> None:
    for src in pal_files():
        rel = src.relative_to(STD_PAL)
        dest = std_src / rel
        if dest.exists():
            sys.exit(f"galexy-std-sysroot: {rel} already exists in std; refusing to overwrite")
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dest)
    generate_abi(std_src / "sys/pal/galexy/abi.rs")


def apply_patches(library: Path) -> None:
    std = library / "std"
    src = std / "src"

    # restricted_std: galexy is a first-class OS for this std.
    patch_text(
        std / "build.rs",
        """        || target_os == "vexos"
""",
        """        || target_os == "vexos"
        || target_os == "galexy"
""",
    )
    # dlmalloc backs `System` (Milestone 70); the same dependency line
    # wasm / xous / vexos / sgx use.
    patch_text(
        std / "Cargo.toml",
        """target_os = "xous", target_os = "vexos", all(target_vendor = "fortanix", target_env = "sgx")))'.dependencies]
dlmalloc""",
        """target_os = "xous", target_os = "vexos", target_os = "galexy", all(target_vendor = "fortanix", target_env = "sgx")))'.dependencies]
dlmalloc""",
    )

    # The PAL itself.
    insert_before(
        src / "sys/pal/mod.rs",
        """    _ => {
        mod unsupported;
        pub use self::unsupported::*;
    }
}
""",
        """    target_os = "galexy" => {
        mod galexy;
        pub use self::galexy::*;
    }
""",
    )

    # Allocator.
    patch_text(
        src / "sys/alloc/mod.rs",
        """    target_os = "zkvm" => {
        mod zkvm;
        use zkvm as imp;
    }
}
""",
        """    target_os = "zkvm" => {
        mod zkvm;
        use zkvm as imp;
    }
    target_os = "galexy" => {
        mod galexy;
        use galexy as imp;
    }
}
""",
    )

    # Randomness: RDRAND with a seeded fallback; the module exports both
    # `fill_bytes` and `hashmap_random_keys`.
    insert_before(
        src / "sys/random/mod.rs",
        """    _ => {}
}
""",
        """    target_os = "galexy" => {
        mod galexy;
        pub use galexy::{fill_bytes, hashmap_random_keys};
    }
""",
    )
    patch_text(
        src / "sys/random/mod.rs",
        """    target_os = "xous",
    target_os = "vexos",
    target_os = "l4re",
)))]
""",
        """    target_os = "xous",
    target_os = "vexos",
    target_os = "l4re",
    target_os = "galexy",
)))]
""",
    )

    # Threads (ThreadSpawn / ThreadExit).
    patch_text(
        src / "sys/thread/mod.rs",
        """    target_os = "hermit" => {
        mod hermit;
        pub use hermit::{DEFAULT_MIN_STACK_SIZE, Thread, available_parallelism, sleep, yield_now};
        #[expect(dead_code)]
        mod unsupported;
        pub use unsupported::{current_os_id, set_name};
    }
""",
        """    target_os = "hermit" => {
        mod hermit;
        pub use hermit::{DEFAULT_MIN_STACK_SIZE, Thread, available_parallelism, sleep, yield_now};
        #[expect(dead_code)]
        mod unsupported;
        pub use unsupported::{current_os_id, set_name};
    }
    target_os = "galexy" => {
        mod galexy;
        pub use galexy::{DEFAULT_MIN_STACK_SIZE, Thread, available_parallelism, sleep, yield_now};
        #[expect(dead_code)]
        mod unsupported;
        pub use unsupported::{current_os_id, set_name};
    }
""",
    )

    # Simple `mod galexy; pub use galexy::*;` dispatchers.
    for rel in ("sys/stdio/mod.rs", "sys/env/mod.rs"):
        insert_before(
            src / rel,
            """    _ => {
        mod unsupported;
        pub use unsupported::*;
    }
}
""",
            """    target_os = "galexy" => {
        mod galexy;
        pub use galexy::*;
    }
""",
        )
    insert_before(
        src / "sys/args/mod.rs",
        """    _ => {
        mod unsupported;
        pub use unsupported::*;
    }
}
""",
        """    target_os = "galexy" => {
        mod galexy;
        pub use galexy::*;
    }
""",
    )
    patch_text(
        src / "sys/args/mod.rs",
        """    target_os = "wasi",
    target_os = "xous",
))]
mod common;
""",
        """    target_os = "wasi",
    target_os = "xous",
    target_os = "galexy",
))]
mod common;
""",
    )

    # `use galexy as imp;` dispatchers.
    for rel in ("sys/time/mod.rs", "sys/fs/mod.rs", "sys/process/mod.rs", "sys/paths/mod.rs"):
        insert_before(
            src / rel,
            """    _ => {
        mod unsupported;
        use unsupported as imp;
    }
}
""",
            """    target_os = "galexy" => {
        mod galexy;
        use galexy as imp;
    }
""",
        )
    insert_before(
        src / "sys/pipe/mod.rs",
        """    _ => {
        mod unsupported;
        pub use unsupported::{Pipe, pipe};
    }
}
""",
        """    target_os = "galexy" => {
        mod galexy;
        pub use galexy::{Pipe, pipe};
    }
""",
    )
    insert_before(
        src / "sys/io/error/mod.rs",
        """    any(target_os = "vexos", target_family = "wasm", target_os = "zkvm", target_os = "trusty") => {
        mod generic;
        pub use generic::*;
    }
}
""",
        """    target_os = "galexy" => {
        mod galexy;
        pub use galexy::*;
    }
""",
    )

    # Futex, and every primitive built on it.
    insert_before(
        src / "sys/sync/futex/mod.rs",
        """    _ => {}
}
""",
        """    target_os = "galexy" => {
        mod galexy;
        pub use galexy::*;
    }
""",
    )
    for prim in ("mutex", "condvar", "rwlock", "once", "thread_parking"):
        patch_text(
            src / f"sys/sync/{prim}/mod.rs",
            """        target_os = "hermit",
""",
            """        target_os = "hermit",
        target_os = "galexy",
""",
        )

    # Key-based TLS (FS base points at a per-thread slot table). The
    # destructor guard is a no-op: `thread_start` runs `destroy_tls` itself.
    tls = src / "sys/thread_local/mod.rs"
    patch_text(
        tls,
        """        target_os = "xous" => {
            mod racy;
            #[cfg(test)]
            mod tests;
            mod xous;
            pub(super) use racy::LazyKey;
            pub(crate) use xous::destroy_tls;
            pub(super) use xous::{Key, get, set};
            use xous::{create, destroy};
        }
""",
        """        target_os = "xous" => {
            mod racy;
            #[cfg(test)]
            mod tests;
            mod xous;
            pub(super) use racy::LazyKey;
            pub(crate) use xous::destroy_tls;
            pub(super) use xous::{Key, get, set};
            use xous::{create, destroy};
        }
        target_os = "galexy" => {
            mod galexy;
            mod racy;
            #[cfg(test)]
            mod tests;
            pub(super) use galexy::{Key, get, set};
            pub(crate) use galexy::destroy_tls;
            pub(super) use racy::LazyKey;
            use galexy::{create, destroy};
        }
""",
    )
    patch_text(
        tls,
        """        any(target_os = "hermit", target_os = "xous") => {
            // `std` is the only runtime, so it just calls the destructor functions
            // itself when the time comes.
            pub(crate) fn enable() {}
        }
""",
        """        any(target_os = "hermit", target_os = "xous", target_os = "galexy") => {
            // `std` is the only runtime, so it just calls the destructor functions
            // itself when the time comes.
            pub(crate) fn enable() {}
        }
""",
    )

    # process::exit.
    patch_text(
        src / "sys/exit.rs",
        """        target_os = "xous" => crate::os::xous::ffi::exit(code as u32),
""",
        """        target_os = "xous" => crate::os::xous::ffi::exit(code as u32),
        target_os = "galexy" => crate::sys::pal::exit(code),
""",
    )

    # std::env::consts.
    insert_before(
        src / "sys/env_consts.rs",
        """#[cfg(target_os = "vexos")]
pub mod os {
""",
        """#[cfg(target_os = "galexy")]
pub mod os {
    pub const FAMILY: &str = "";
    pub const OS: &str = "galexy";
    pub const DLL_PREFIX: &str = "";
    pub const DLL_SUFFIX: &str = "";
    pub const DLL_EXTENSION: &str = "";
    pub const EXE_SUFFIX: &str = "";
    pub const EXE_EXTENSION: &str = "";
}

""",
    )

    # std::os::galexy (OsStr/OsString byte extension traits).
    patch_text(
        src / "os/mod.rs",
        """#[cfg(target_os = "fuchsia")]
pub mod fuchsia;
""",
        """#[cfg(target_os = "fuchsia")]
pub mod fuchsia;
#[cfg(target_os = "galexy")]
pub mod galexy;
""",
    )


def patch_library(library: Path) -> None:
    """Install the PAL into a rust checkout's `library/` (Milestone 72)."""
    if not (library / "std/src").is_dir():
        sys.exit(f"galexy-std-sysroot: not a library tree: {library}")
    stamp = library / ".galexy-pal"
    if stamp.is_file():
        return
    install_pal(library / "std/src")
    apply_patches(library)
    stamp.write_text("milestone-72\n")


def main() -> None:
    if len(sys.argv) == 3 and sys.argv[1] == "--patch-library":
        patch_library(Path(sys.argv[2]).resolve())
        return
    if len(sys.argv) != 3 or sys.argv[1] != "--out":
        sys.exit("usage: galexy-std-sysroot.py --out DIR | --patch-library LIBRARY")
    out = Path(sys.argv[2]).resolve()
    real = rustc_sysroot()
    real_lib = real / "lib/rustlib/src/rust/library"
    if not real_lib.is_dir():
        sys.exit(f"galexy-std-sysroot: rust-src missing at {real_lib}")
    if not STD_PAL.is_dir():
        sys.exit(f"galexy-std-sysroot: std-pal tree missing at {STD_PAL}")

    version = subprocess.check_output(
        [os.environ.get("RUSTC", "rustc"), "--version"], text=True
    ).strip()
    digest = hashlib.sha256()
    digest.update(Path(__file__).read_bytes())
    digest.update(ABI_SRC.read_bytes())
    for p in pal_files():
        digest.update(str(p.relative_to(STD_PAL)).encode())
        digest.update(p.read_bytes())
    stamp_body = f"{version}\n{PATCH_VERSION}\n{real}\n{digest.hexdigest()}\n"
    # Content-addressed: cargo does not record build-script source paths
    # that live under a target directory, so a changed overlay at the same
    # path would reuse std's stale `build.rs` binary (and its cfgs). A new
    # package root per content gives cargo a new fingerprint instead.
    key = hashlib.sha256(stamp_body.encode()).hexdigest()[:16]
    slot = out / key
    stamp = slot / ".galexy-std-stamp"
    sysroot = slot / "sysroot"
    if stamp.is_file() and stamp.read_text() == stamp_body and sysroot.is_dir():
        print(sysroot)
        return

    if out.exists():
        shutil.rmtree(out)
    rustlib = sysroot / "lib/rustlib"
    rustlib.mkdir(parents=True)
    for child in (real / "lib/rustlib").iterdir():
        if child.name == "src":
            continue
        (rustlib / child.name).symlink_to(child)
    library = rustlib / "src/rust/library"
    shutil.copytree(real_lib, library, symlinks=True)
    install_pal(library / "std/src")
    apply_patches(library)
    stamp.write_text(stamp_body)
    print(sysroot)


if __name__ == "__main__":
    main()
